"""Core-side glue for KARMO's local eyes -- dispatches an image + question
to a worker's vision_describe capability (worker-runtime/app/capabilities.py)
and waits for the result, via the same worker_dispatch_client used by
Model Router Phase D2.

Verified live 2026-09-20: Worker01 pulled moondream (1.74GB), described a
real screenshot correctly in 8.13s, using ~1.3GB RAM with ~7GB still free
afterward -- see docs/plans/KARMO_VOICE_VISION_EARS_ROADMAP.md.

**Deliberately NOT wired into _CHAT_EXPOSED_TOOLS.** A chat tool's
arguments are generated by the local text model itself -- there is no way
for qwen3:8b to invent real image bytes as a tool-call argument, and no
KARMO client surface (webui, phone) can capture and pass one in yet
(Phase V3 of the roadmap, still undecided). This module is the Core-side
capability a real client surface would call once one exists, exposed here
as a plain function so it can be built, tested, and proven correct now
without waiting on that decision.

**Deliberately NOT activated.** dispatch_vision_describe() requires
worker_dispatch_client.available to be True, which requires
/etc/karmo/core/worker-dispatch.dsn to exist -- and that file has been
deliberately left uncreated since Phase D2 (see worker_dispatch_client.py
and CURRENT_STATE.md's 2026-09-19 D2 entry: two independent reviews found
real gaps -- an over-privileged credential, no retention policy for
worker-stored content, a check-then-act worker-selection race -- and
Kamara chose to hold activation). That switch is shared: operator.py's
_chat() also gates D2's live chat-routing-to-worker path on the exact
same worker_dispatch_client.available flag. Creating the DSN file to
enable vision dispatch would therefore ALSO silently re-enable D2's
held-back chat routing, as a side effect neither reviewed nor decided.
Do not create that DSN file to activate this module without first either
resolving D2's own flagged concerns, or decoupling the two switches (a
separate, real piece of work, not done here).
"""

from __future__ import annotations

VISION_DESCRIBE_TOOL_ID = "vision_describe"
VISION_DESCRIBE_TOOL_VERSION = "1.0.0"
_DEFAULT_WORKER_ID = "KARMO-WORKER01"

MAX_QUESTION_CHARS = 2000
MAX_IMAGE_BYTES_BASE64 = 7_000_000  # ~5MB decoded, matching the worker's own cap, plus base64 overhead


class VisionCapabilityError(RuntimeError):
    pass


def manifest() -> dict:
    return {
        "tool_id": VISION_DESCRIBE_TOOL_ID,
        "domain": "vision",
        "version": VISION_DESCRIBE_TOOL_VERSION,
        "description": (
            "Describe or answer a question about an image using KARMO's own local vision "
            "model (moondream), running on a worker -- not Claude or GPT. Requires a real "
            "client surface to supply the image; not currently reachable from chat."
        ),
        "input_schema": {
            "type": "object",
            "properties": {
                "question": {"type": "string", "maxLength": MAX_QUESTION_CHARS},
                "image_base64": {"type": "string"},
            },
            "required": ["question", "image_base64"],
            "additionalProperties": False,
        },
        "output_schema": {"type": "object", "properties": {"answer": {"type": "string"}}},
        "capability_class": "READ",
        "read_scope": "none -- dispatches to a worker's own loopback Ollama only",
        "write_scope": "none",
        "external_side_effects": "one dispatched job to a worker via the existing worker-coordination path",
        "financial_action": False,
        "destructive_action": False,
        "network_requirements": "none from Core's perspective -- LAN dispatch to an already-authenticated worker",
        "secret_requirements": "none beyond the existing worker-dispatch DSN, when provisioned",
        "invocation_identity": "karmo-chat-model",
        "timeout_seconds": 60,
        "retry_policy": "none",
        "idempotent": False,
        "idempotency_mechanism": "not idempotent; each call is a live model invocation on a worker",
        "rollback_or_compensation": "not applicable",
        "health_check": "invoke with a trivial image and question, confirm a non-empty answer",
        "deprecation_policy": "explicit version replacement",
        "dependencies": "worker_dispatch_client.available (requires /etc/karmo/core/worker-dispatch.dsn -- see module docstring for why this is not yet created)",
        "observability": "structured operator response",
        "failure_isolation": "a dispatch failure or timeout refuses cleanly, never hangs the chat turn",
    }


def dispatch_vision_describe(
    worker_dispatch_client,
    *,
    worker_id: str,
    question: str,
    image_base64: str,
    total_deadline_seconds: float = 60.0,
) -> str:
    """Dispatches one vision_describe job to worker_id and returns the
    answer text, or raises VisionCapabilityError with a clean, honest
    reason -- never a raw worker/dispatch exception leaking upward."""
    if not isinstance(question, str) or not question.strip():
        raise VisionCapabilityError("question must be non-empty text")
    if len(question) > MAX_QUESTION_CHARS:
        raise VisionCapabilityError(f"question exceeds {MAX_QUESTION_CHARS} characters")
    if not isinstance(image_base64, str) or not image_base64.strip():
        raise VisionCapabilityError("image_base64 must be non-empty text")
    if len(image_base64) > MAX_IMAGE_BYTES_BASE64:
        raise VisionCapabilityError(f"image_base64 exceeds {MAX_IMAGE_BYTES_BASE64} characters")
    if not worker_dispatch_client.available:
        raise VisionCapabilityError(
            "worker dispatch is not activated -- no worker-dispatch DSN configured"
        )

    outcome = worker_dispatch_client.dispatch(
        worker_id=worker_id,
        tool_id=VISION_DESCRIBE_TOOL_ID,
        tool_version=VISION_DESCRIBE_TOOL_VERSION,
        arguments={"model": "moondream", "question": question, "image_base64": image_base64},
        total_deadline_seconds=total_deadline_seconds,
    )
    if outcome.outcome != "SUCCEEDED" or not isinstance(outcome.result, dict):
        raise VisionCapabilityError(f"{outcome.outcome}: {outcome.error}")
    answer = outcome.result.get("answer")
    if not isinstance(answer, str):
        raise VisionCapabilityError("worker returned an invalid vision_describe result")
    return answer


def handler(worker_dispatch_client, *, worker_id: str = _DEFAULT_WORKER_ID):
    """Returns a dispatcher-bindable (arguments) -> dict handler closure,
    same shape as code_assist_capability.handler(). Registering this with
    KarmoOperator's dispatcher does NOT add it to _CHAT_EXPOSED_TOOLS --
    it makes the capability reachable through the same
    CapabilityDispatcher/ApprovalEngine authority path for a real client
    surface (e.g. the webui) to call directly, once one exists."""
    def _handler(arguments: dict) -> dict:
        answer = dispatch_vision_describe(
            worker_dispatch_client,
            worker_id=worker_id,
            question=arguments.get("question"),
            image_base64=arguments.get("image_base64"),
        )
        return {"answer": answer}
    return _handler
